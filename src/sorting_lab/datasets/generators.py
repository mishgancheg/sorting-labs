"""Параметрические генераторы наборов данных для проверки сортировок.

Все генераторы возвращают новый список целых чисел и принимают два общих
параметра:

- ``n`` — размер генерируемого массива;
- ``seed`` — случайное зерно (число, полностью определяющее «случайность»).
  Одинаковое зерно даёт одинаковый массив на любой машине и в любое время —
  это условие воспроизводимости результатов НИР: любой прогон можно повторить
  в точности.

Типы входов подобраны под особенности алгоритмов из архива статей:
почти отсортированные данные важны адаптивным сортировкам (Splitsort,
adaptive heapsort), входы с большим числом повторов — алгоритмам с
«разделением» (pattern-defeating подходам), обратно отсортированные —
худшие случаи для наивной быстрой сортировки.
"""

from __future__ import annotations

import random


def random_uniform(n: int, seed: int = 0) -> list[int]:
    """Массив случайных целых чисел из диапазона 0..n-1 (равномерно).

    Стандартный «нейтральный» вход: средний случай для большинства
    алгоритмов, оценка O(n log n) достигается именно на нём.
    """
    rng = random.Random(seed)
    return [rng.randrange(n) for _ in range(n)]


def sorted_ascending(n: int, seed: int = 0) -> list[int]:
    """Уже отсортированный по возрастанию массив 0, 1, 2, ..., n-1.

    Лучший случай для адаптивных сортировок: число инверсий равно нулю,
    и они должны завершить работу почти без сравнений.
    Параметр ``seed`` не используется, но оставлен для единства интерфейса.
    """
    return list(range(n))


def sorted_descending(n: int, seed: int = 0) -> list[int]:
    """Отсортированный по убыванию массив: n-1, n-2, ..., 1, 0.

    Максимум возможных инверсий (все пары «неправильны») — вход, на котором
    видна разница между обычными и адаптивными алгоритмами.
    """
    return list(range(n - 1, -1, -1))


def nearly_sorted(n: int, seed: int = 0, disorder: float = 0.05) -> list[int]:
    """Почти отсортированный массив: отсортированный вход с небольшими сбоями.

    Сначала берётся массив 0..n-1, затем случайные пары соседних элементов
    меняются местами. Параметр ``disorder`` — доля таких обменов от размера
    массива (от 0.0 до 1.0): чем меньше, тем ближе вход к отсортированному.
    На этом входе адаптивные алгоритмы должны заметно опережать обычные.
    """
    rng = random.Random(seed)
    data = list(range(n))
    swaps = int(n * disorder)
    for _ in range(swaps):
        i = rng.randrange(n - 1)
        data[i], data[i + 1] = data[i + 1], data[i]
    return data


def few_unique(n: int, seed: int = 0, values: int = 5) -> list[int]:
    """Массив из небольшого числа повторяющихся значений (по умолчанию 5).

    Много равных элементов — проверка корректности обработки равенства и
    «распознавания паттернов» (pattern defeating) в новых quicksort-ах.
    """
    rng = random.Random(seed)
    return [rng.randrange(values) for _ in range(n)]


def sawtooth(n: int, seed: int = 0, teeth: int = 10) -> list[int]:
    """«Пилообразный» вход: несколько возрастающих серий, следующих друг за другом.

    Каждая серия («зуб пилы») — числа 0..k-1, где k = n // teeth. Такой вход
    состоит из заранее готовых отсортированных подпоследовательностей —
    характерная проверка для сортировок на основе слияния run'ов
    (Powersort, TimSort-подобные).
    """
    tooth_length = max(1, n // teeth)
    return [i % tooth_length for i in range(n)]


