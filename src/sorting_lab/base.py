"""Базовые определения для всех алгоритмов сортировки.

Каждый алгоритм фреймворка наследуется от класса :class:`Algorithm` и
обязуется уметь сортировать любую изменяемую последовательность, используя
для сравнения элементов переданный компаратор.

Компаратор — это функция двух аргументов, возвращающая:
    отрицательное число, если первый элемент должен идти раньше второго;
    ноль, если элементы равны с точки зрения порядка;
    положительное число, если первый элемент должен идти позже второго.

Такой контракт нужен, чтобы измерительный стенд мог подставить вместо
обычного сравнения компаратор-счётчик и точно подсчитать число сравнений
(см. ``sorting_lab.bench.metrics``). Если алгоритм сравнивает элементы
оператором ``<`` напрямую, подсчёт становится невозможным — поэтому это
запрещено соглашениями проекта (см. CLAUDE.md).
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any, Callable, MutableSequence

# Стандартная сигнатура компаратора: принимает два элемента, возвращает целое число.
Comparator = Callable[[Any, Any], int]


def default_compare(first: Any, second: Any) -> int:
    """Компаратор по умолчанию: сравнение через операторы ``<`` и ``>``.

    Работает для любых элементов, поддерживающих эти операторы
    (числа, строки, кортежи и так далее).
    """
    if first < second:
        return -1
    if first > second:
        return 1
    return 0


@dataclass(frozen=True)
class AlgorithmInfo:
    """Паспорт алгоритма: формальные сведения, взятые из статьи-источника.

    Атрибуты:
        name: короткое имя-идентификатор, по которому алгоритм ищется в реестре
            (например, ``"heapsort"``);
        full_name: полное название на языке оригинала статьи;
        reference: статья-источник, откуда взята реализация и теория;
        time_complexity: оценка времени в худшем случае, запись в терминах
            большого O (например, ``"O(n log n)"``);
        space_complexity: оценка дополнительной памяти;
        stable: устойчивость — сохраняет ли алгоритм относительный порядок
            равных элементов;
        in_place: работает ли алгоритм на месте, то есть без вспомогательного
            массива размера, сопоставимого с входом;
        notes: свободные пояснения (особенности, допущения реализации).
    """

    name: str
    full_name: str
    reference: str
    time_complexity: str
    space_complexity: str
    stable: bool
    in_place: bool
    notes: str = ""


class Algorithm(ABC):
    """Абстрактный базовый класс всякого алгоритма сортировки проекта.

    Наследник обязан определить атрибут ``info`` (паспорт алгоритма) и метод
    :meth:`sort`. Регистрация в реестре происходит в модуле
    ``sorting_lab.registry``.
    """

    #: Паспорт алгоритма; заполняется в каждом наследнике.
    info: AlgorithmInfo = field(init=False)

    @abstractmethod
    def sort(self, data: MutableSequence[Any], compare: Comparator = default_compare) -> None:
        """Отсортировать последовательность ``data`` по неубыванию.

        Аргументы:
            data: изменяемая последовательность (список, массив numpy и т. п.);
                сортировка выполняется на месте, копия не создаётся;
            compare: компаратор — функция сравнения двух элементов,
                описание контракта см. в docstring модуля.

        Возвращаемого значения нет: результат записывается прямо в ``data``.
        """
        raise NotImplementedError
